import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const recordsDir = path.join(root, "content/media/records");
const generatedDir = path.join(root, "content/media/wikimedia");
const output = path.join(root, "apps/instructor-editor/src/generated-legacy-artifacts.ts");
const publicOrigin = "https://ethicsandai.your-digital-life.org";

const readJson = async (file) => JSON.parse(await readFile(file, "utf8"));
const entries = [];

for (const filename of (await readdir(recordsDir)).filter((name) => name.endsWith(".json")).sort()) {
  const record = await readJson(path.join(recordsDir, filename));
  if (!Array.isArray(record.placements) || record.placements.length === 0) continue;
  const generated = await readJson(path.join(generatedDir, filename));
  for (const placement of record.placements) {
    const passageId = Array.isArray(placement.passageIds) ? placement.passageIds.find(Boolean) : undefined;
    if (!placement.chapterId || !passageId) continue;
    entries.push({
      artifactId: record.id,
      chapterId: `chapter_${placement.chapterId}`,
      anchorPassageId: `passage_${passageId}`,
      title: record.title,
      alt: record.decorative ? "" : record.alt,
      caption: record.caption ?? "",
      teachingUse: record.teachingUse,
      artifactType: record.artifactType ?? "visual source",
      src: `${publicOrigin}${generated.derivative.localPath}`,
      width: generated.derivative.width,
      height: generated.derivative.height,
      sourceUrl: generated.source.pageUrl,
      creator: generated.rights.artist,
      license: generated.rights.licenseShortName,
      licenseUrl: generated.rights.licenseUrl ?? "",
      reviewedRevision: String(generated.source.revisionId ?? ""),
      modification: generated.derivative.modification ?? "Reviewed web derivative.",
    });
  }
}

entries.sort((left, right) => `${left.chapterId}:${left.anchorPassageId}:${left.artifactId}`.localeCompare(`${right.chapterId}:${right.anchorPassageId}:${right.artifactId}`));
await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, `// Generated by scripts/generate-editor-legacy-artifacts.mjs. Do not edit.\nexport const legacyCuratedArtifacts = ${JSON.stringify(entries, null, 2)} as const;\n`);
console.log(`Generated ${entries.length} legacy editor artifact placements.`);
